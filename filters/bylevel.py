def filter_bylevel(data, min_level, max_level=None, max=False):
    results = []
    if not max:
        for chart in data["results"]:
            if min_level == chart["level"]:
                results.append(chart)

    if max:
        for chart in data["results"]:
            if min_level <= chart["level"] <= max_level:
                results.append(chart)
    return results

